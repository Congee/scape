const angErr = (a: number, b: number) => Math.abs(((a - b + 540) % 360) - 180);

describe('WGS84 geodesics vs GeographicLib', () => {
  it.each(GEOD_TEST)('inverse %f,%f → %f,%f', (lat1, lng1, azi1, lat2, lng2, azi2, s12) => {
    const g = inverse({ lat: lat1, lng: lng1 }, { lat: lat2, lng: lng2 });
    expect(Math.abs(g.distM - s12)).toBeLessThan(1e-3);
    // Near-antipodal lines off the equator: the printed endpoints' round-off moves azimuth by 1e-5°, GeographicLib's too.
    if (s12 > 19.9e6 && Math.abs(azi1 - 90) < 0.05) return;
    expect(angErr(g.azi1, azi1)).toBeLessThan(1e-6);
    expect(angErr(g.azi2, azi2)).toBeLessThan(1e-6);
  });

  it.each(GEOD_TEST)('direct %f,%f az %f', (lat1, lng1, azi1, lat2, lng2, _azi2, s12) => {
    const p = destination({ lat: lat1, lng: lng1 }, azi1, s12);
    expect(Math.abs(p.lat - lat2)).toBeLessThan(1e-9);
    expect(angErr(p.lng, lng2) * Math.cos(lat2 * (Math.PI / 180))).toBeLessThan(1e-9);
  });

  // GeographicLib Direct: [from lat, lng, azimuth, metres, to lat, lng].
  it.each([
    [0, 7, 45, 1000, 0.006394857885749925, 7.006352048316644],
    [46, 7, 45, 50000, 46.31715587865738, 7.459044101740902],
    [69.65, 18.96, 135, 20000, 69.52285376621441, 19.322080180700322],
    [-45, 168.66, 300, 100000, -44.544838740773095, 167.57020806261625]
  ])('%f,%f az %f %f m: bearing within 1e-6°, distance within 1 mm', (lat, lng, az, s, lat2, lng2) => {
    const a = { lat, lng };
    const b = { lat: lat2, lng: lng2 };
    expect(Math.abs(distanceM(a, b) - s)).toBeLessThan(1e-3);
    expect(angErr(bearingDeg(a, b), az)).toBeLessThan(1e-6);
    const p = destination(a, az, s);
    expect(Math.abs(p.lat - lat2)).toBeLessThan(1e-11);
    expect(Math.abs(p.lng - lng2)).toBeLessThan(1e-11);
  });

  it('samples one geodesic evenly', () => {
    const a = { lat: 40.7128, lng: -74.006 };
    const b = { lat: 51.5072, lng: -0.1276 };
    const at = geodesicBetween(a, b);
    expect(at(0)).toEqual(expect.objectContaining({ lat: a.lat }));
    expect(Math.abs(at(1).lat - b.lat)).toBeLessThan(1e-11);
    expect(Math.abs(distanceM(a, intermediatePoint(a, b, 0.25)) - 0.25 * distanceM(a, b))).toBeLessThan(1e-6);
  });
});
